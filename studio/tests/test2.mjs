await p.goto('http://localhost:8765/index.html#medias'); await p.waitForTimeout(600);
await p.setInputFiles('#file', {name: 'video4_hook_gobelet_FINALE (1).mp4', mimeType: 'video/mp4', buffer: fs.readFileSync('/home/user/projet/video/out/drive/video11_fennec_alan_FINALE.mp4')});
await p.waitForTimeout(4000);
console.log(JSON.stringify((await p.evaluate(() => window.__log)).filter((x) => x[0] === 'upload' || x[1] === 'media')));
console.log('errors', JSON.stringify(errs)); await b.close();
