const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.addInitScript(`window.__SEED=${seed};` + mock);
await p.goto('http://localhost:8765/index.html#post-a-short1'); await p.waitForTimeout(900);
console.log('video muted before', await p.evaluate(() => document.querySelector('#pv-video')?.muted));
